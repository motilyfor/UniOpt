#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR_ARG="${1:-}"
if [ -z "$OUT_DIR_ARG" ]; then
    echo "Usage: $0 <out_dir>"
    exit 1
fi

ARGS_FILE="${OUT_DIR_ARG}/args.gn"
OUT_FILE="${OUT_DIR_ARG}/generated_build.gni"
HASH_FILE="${OUT_DIR_ARG}/.build_hash"

# compute hash of all BUILD.gn under repo (excluding out/)
compute_src_hash() {
    find "$ROOT_DIR" -type f -name BUILD.gn -not -path "*/out/*" -print0 | sort -z | xargs -0 sha1sum 2>/dev/null | sha1sum | awk '{print $1}' || true
}

NEW_HASH="$(compute_src_hash)"
OLD_HASH=""
if [ -f "$HASH_FILE" ]; then
    OLD_HASH=$(cat "$HASH_FILE" || true)
fi

if [ -f "$OUT_FILE" ] && [ "$NEW_HASH" = "$OLD_HASH" ]; then
    echo "generated_build.gni up-to-date; skipping generation"
    exit 0
fi

# extract build_target label from args.gn (strip quotes)
BUILD_TARGET_LABEL=""
if [ -f "$ARGS_FILE" ]; then
    BUILD_TARGET_LABEL=$(sed -nE 's/^build_target\s*=\s*(.*)/\1/p' "$ARGS_FILE" || true)
    BUILD_TARGET_LABEL=$(echo "$BUILD_TARGET_LABEL" | sed -E 's/^"(.*)"$/\1/')
    BUILD_TARGET_LABEL=$(echo "$BUILD_TARGET_LABEL" | sed -E "s/^'(.+)'$/\1/")
fi

cat > "$OUT_FILE" <<EOF
# generated by build/generate_root_BUILD_gn.sh
# DO NOT COMMIT generated_build.gni

# This file exports a variable `generated_default_deps` which the top-level
# BUILD.gn may append into its `group("default").deps`.
generated_default_deps = [
EOF

if [ -n "$BUILD_TARGET_LABEL" ]; then
    printf '  "%s"\n' "$BUILD_TARGET_LABEL" >> "$OUT_FILE"
else
    printf '  build_target\n' >> "$OUT_FILE"
fi

cat >> "$OUT_FILE" <<'EOF'
]
EOF

echo "$NEW_HASH" > "$HASH_FILE"
echo "Wrote generated build file at ${OUT_FILE} (hash updated)"

exit 0
